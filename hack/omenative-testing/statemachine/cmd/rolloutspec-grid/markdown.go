package main

import (
	"fmt"
	"io"
	"sort"
	"strings"
	"unicode/utf8"

	"github.com/ome-projects/ome/tests/rolloutspec"
)

// maxMarkdownNoteChars bounds a note rendered in the "What else happens
// here" table, in runes, so one verbose cell note cannot blow out an
// otherwise scannable table row. The JSON envelope carries the full note.
const maxMarkdownNoteChars = 140

// emitMarkdown renders a machine as a narrative document: one section per
// state, meant to be read top to bottom, unlike the json and mermaid
// formats which expose the grid or the transitions for a machine to
// consume.
func emitMarkdown(w io.Writer, m *rolloutspec.Machine) error {
	var b strings.Builder
	writeMarkdownHeader(&b, m)
	writeStatesOverview(&b, m)
	writeInvariants(&b, m)
	for i := range m.States {
		writeStateSection(&b, m, &m.States[i])
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func writeMarkdownHeader(b *strings.Builder, m *rolloutspec.Machine) {
	fmt.Fprintf(b, "# %s machine — reader's view\n\n", m.Machine)
	fmt.Fprintf(b, "%s. %d states, %d events, %d transitions, %d authored cells.\n",
		m.Scope, len(m.States), len(m.Events), len(m.Transitions), len(m.Cells))
	fmt.Fprintf(b, "Generated by rolloutspec-grid; do not edit — regenerate with `make rolloutspec-render MACHINE=%s`.\n\n", m.Machine)
}

func writeStatesOverview(b *strings.Builder, m *rolloutspec.Machine) {
	incoming, outgoing := transitionAdjacency(m)
	b.WriteString("## States at a glance\n\n")
	b.WriteString("| state | phase | operation | step | applies | entered from | leaves to |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, s := range m.States {
		op, step := "—", "—"
		if s.Op != nil {
			op, step = s.Op.Type, s.Op.Step
		}
		writeTableRow(b, []string{
			s.ID, s.Phase, op, step, renderApplies(s.Applies),
			joinOrDash(incoming[s.ID]), joinOrDash(outgoing[s.ID]),
		})
	}
	b.WriteString("\n")
}

// writeInvariants renders the machine-wide properties cells cite by id, so
// a reader meeting an id in a cell can look up what it asserts. A machine
// that declares none gets no section rather than an empty table.
func writeInvariants(b *strings.Builder, m *rolloutspec.Machine) {
	if len(m.Invariants) == 0 {
		return
	}
	b.WriteString("## Invariants\n\n")
	b.WriteString("| id | statement |\n")
	b.WriteString("| --- | --- |\n")
	for _, inv := range m.Invariants {
		writeTableRow(b, []string{inv.ID, inv.Statement})
	}
	b.WriteString("\n")
}

func writeStateSection(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	fmt.Fprintf(b, "## %s\n\n", s.ID)

	opText := "no operation"
	if s.Op != nil {
		opText = fmt.Sprintf("operation `%s`/`%s`", s.Op.Type, s.Op.Step)
	}
	fmt.Fprintf(b, "Phase `%s`, %s. Decided in `%s`.\n", s.Phase, opText, s.DecidedIn)
	if s.Note != "" {
		fmt.Fprintf(b, "%s\n", s.Note)
	}
	b.WriteString("\n")

	writeHowYouGetHere(b, m, s)
	writeHowYouLeave(b, m, s)
	writeWhatElseHappens(b, m, s)
	writeIgnoredHere(b, m, s)
	writeNeverHappensHere(b, s)
	writeOpenDecisions(b, m, s)
}

func writeHowYouGetHere(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	b.WriteString("**How you get here**\n\n")
	var found bool
	for _, t := range m.Transitions {
		if t.To != s.ID {
			continue
		}
		found = true
		fmt.Fprintf(b, "- from `%s` on %s when %s  (`%s`)\n", t.From, renderEventVariant(t.Event, transitionVariants(t)), t.Guard, t.ID)
	}
	if !found {
		b.WriteString("Nothing declared; this is a start state.\n")
	}
	b.WriteString("\n")
}

func writeHowYouLeave(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	b.WriteString("**How you leave**\n\n")
	var found bool
	for _, t := range m.Transitions {
		if t.From != s.ID {
			continue
		}
		found = true
		fmt.Fprintf(b, "- on %s when %s → `%s`  (`%s`)\n", renderEventVariant(t.Event, transitionVariants(t)), t.Guard, t.To, t.ID)
	}
	if !found {
		b.WriteString("Nothing declared; this is a terminal state.\n")
	}
	b.WriteString("\n")
}

// transitionVariants adapts Transition.Variant, a single string where blank
// means "any variant", to the []string form renderEventVariant expects.
func transitionVariants(t rolloutspec.Transition) []string {
	if t.Variant == "" {
		return nil
	}
	return []string{t.Variant}
}

func writeWhatElseHappens(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	b.WriteString("**What else happens here**\n\n")
	b.WriteString("| event | windows | transition | outcome | to | note |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for i := range m.Cells {
		c := &m.Cells[i]
		if c.State != s.ID {
			continue
		}
		if c.Outcome == rolloutspec.OutcomeIgnore || c.Outcome == rolloutspec.OutcomeNA {
			continue
		}
		windows := "all"
		if len(c.Windows) > 0 {
			windows = strings.Join(c.Windows, ", ")
		}
		outcome := c.Outcome
		if c.Status == rolloutspec.StatusReview {
			outcome += " (review)"
		}
		writeTableRow(b, []string{
			renderEventVariant(c.Event, c.Variants),
			windows,
			c.Transition,
			outcome,
			c.To,
			truncateNote(c.Note),
		})
	}
	b.WriteString("\n")
}

// writeIgnoredHere lists each event[variant] key, as authored, whose every
// cell for this state resolves to ignore: a reader scanning "what else
// happens here" still needs to know an event was considered and dismissed,
// not merely never mentioned.
func writeIgnoredHere(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	keys := ignoredEventKeys(m, s)
	if len(keys) == 0 {
		return
	}
	fmt.Fprintf(b, "**Ignored here**: %s\n\n", strings.Join(keys, ", "))
}

func ignoredEventKeys(m *rolloutspec.Machine, s *rolloutspec.State) []string {
	type group struct {
		allIgnore bool
	}
	var order []string
	groups := map[string]*group{}
	for i := range m.Cells {
		c := &m.Cells[i]
		if c.State != s.ID {
			continue
		}
		key := renderEventVariant(c.Event, c.Variants)
		g, ok := groups[key]
		if !ok {
			g = &group{allIgnore: true}
			groups[key] = g
			order = append(order, key)
		}
		if c.Outcome != rolloutspec.OutcomeIgnore {
			g.allIgnore = false
		}
	}
	var out []string
	for _, k := range order {
		if groups[k].allIgnore {
			out = append(out, k)
		}
	}
	return out
}

// writeNeverHappensHere renders State.NotApplicable, sorted by key so the
// output is stable regardless of map iteration order.
func writeNeverHappensHere(b *strings.Builder, s *rolloutspec.State) {
	if len(s.NotApplicable) == 0 {
		return
	}
	keys := make([]string, 0, len(s.NotApplicable))
	for k := range s.NotApplicable {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%s (%s)", k, s.NotApplicable[k])
	}
	fmt.Fprintf(b, "**Never happens here**: %s\n\n", strings.Join(parts, ", "))
}

func writeOpenDecisions(b *strings.Builder, m *rolloutspec.Machine, s *rolloutspec.State) {
	var lines []string
	for i := range m.Cells {
		c := &m.Cells[i]
		if c.State != s.ID || c.Outcome != rolloutspec.OutcomeDecide {
			continue
		}
		windows := "all"
		if len(c.Windows) > 0 {
			windows = strings.Join(c.Windows, ", ")
		}
		lines = append(lines, fmt.Sprintf("%s (windows: %s): %s", renderEventVariant(c.Event, c.Variants), windows, c.Note))
	}
	if len(lines) == 0 {
		return
	}
	b.WriteString("**Open decisions**\n\n")
	for _, l := range lines {
		fmt.Fprintf(b, "- %s\n", l)
	}
	b.WriteString("\n")
}

// renderEventVariant renders an event id with its variant selector: plain
// when there is no variant, "event[v]" for exactly one, and "event[a|b]"
// for several, matching how a machine table author writes a variant list.
func renderEventVariant(event string, variants []string) string {
	switch len(variants) {
	case 0:
		return event
	case 1:
		return event + "[" + variants[0] + "]"
	default:
		return event + "[" + strings.Join(variants, "|") + "]"
	}
}

// renderApplies renders a state's strategy/shape narrowing the way the
// reader's view table shows it: "any" when the state applies everywhere,
// otherwise the non-empty halves joined with "; ".
func renderApplies(a *rolloutspec.Applies) string {
	if a == nil {
		return "any"
	}
	var parts []string
	if len(a.Strategies) > 0 {
		parts = append(parts, "strategies: "+strings.Join(a.Strategies, ", "))
	}
	if len(a.Shape) > 0 {
		parts = append(parts, "shape: "+strings.Join(a.Shape, ", "))
	}
	if len(parts) == 0 {
		return "any"
	}
	return strings.Join(parts, "; ")
}

// transitionAdjacency derives, for every state, the distinct source states
// of its incoming transitions and the distinct target states of its
// outgoing transitions, each in first-declared order.
func transitionAdjacency(m *rolloutspec.Machine) (incoming, outgoing map[string][]string) {
	incoming = map[string][]string{}
	outgoing = map[string][]string{}
	for _, t := range m.Transitions {
		incoming[t.To] = appendDistinct(incoming[t.To], t.From)
		outgoing[t.From] = appendDistinct(outgoing[t.From], t.To)
	}
	return incoming, outgoing
}

func appendDistinct(list []string, v string) []string {
	for _, x := range list {
		if x == v {
			return list
		}
	}
	return append(list, v)
}

func joinOrDash(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	return strings.Join(items, ", ")
}

// truncateNote bounds a note to maxMarkdownNoteChars runes, cutting on a
// rune boundary so a multi-byte character is never split, and marks a cut
// note with an ellipsis.
func truncateNote(note string) string {
	if utf8.RuneCountInString(note) <= maxMarkdownNoteChars {
		return note
	}
	runes := []rune(note)
	return string(runes[:maxMarkdownNoteChars]) + ellipsis
}

// writeTableRow writes one markdown table row, escaping the pipe character
// in every cell so a note or guard that happens to contain one cannot be
// mistaken for a column separator.
func writeTableRow(b *strings.Builder, cells []string) {
	escaped := make([]string, len(cells))
	for i, c := range cells {
		escaped[i] = strings.ReplaceAll(c, "|", "\\|")
	}
	b.WriteString("| " + strings.Join(escaped, " | ") + " |\n")
}
