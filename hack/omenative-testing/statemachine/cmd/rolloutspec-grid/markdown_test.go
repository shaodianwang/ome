func TestEmitMarkdownReviewAndDecideAnnotations(t *testing.T) {
	m := &rolloutspec.Machine{
		Machine: "demo",
		Scope:   "annotation fixture",
		States:  []rolloutspec.State{{ID: "A", DecidedIn: "doc.go"}},
		Events:  []rolloutspec.Event{{ID: "e"}, {ID: "f"}},
		Cells: []rolloutspec.Cell{
			{State: "A", Event: "e", Outcome: rolloutspec.OutcomeDefer, Status: rolloutspec.StatusReview},
			{State: "A", Event: "f", Outcome: rolloutspec.OutcomeDecide, Status: rolloutspec.StatusCurrent, Note: "pick an outcome"},
		},
	}
	var buf bytes.Buffer
	require.NoError(t, emitMarkdown(&buf, m))
	out := buf.String()

	require.Contains(t, out, "defer (review)")
	require.Contains(t, out, "| DECIDE |")
	require.NotContains(t, out, "DECIDE (DECIDE)")
	require.Contains(t, out, "**Open decisions**\n\n- f (windows: all): pick an outcome\n")
}
