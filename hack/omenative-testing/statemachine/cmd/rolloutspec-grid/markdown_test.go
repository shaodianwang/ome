func loadFixtureMachine(t *testing.T) *rolloutspec.Machine {
	t.Helper()
	m, err := rolloutspec.Load("_fixture")
	require.NoError(t, err)
	return m
}

// stateSection extracts the text of one "## <id>" section, up to the next
// "## " heading or the end of the document, so a test can assert on one
// state without tripping over another state's content.
func stateSection(t *testing.T, doc, id string) string {
	t.Helper()
	start := strings.Index(doc, "## "+id+"\n")
	require.GreaterOrEqualf(t, start, 0, "section %q not found in:\n%s", id, doc)
	rest := doc[start+len("## "+id+"\n"):]
	if next := strings.Index(rest, "\n## "); next >= 0 {
		rest = rest[:next]
	}
	return rest
}

func TestEmitMarkdownHeadingStructure(t *testing.T) {
	var buf bytes.Buffer
	require.NoError(t, emitMarkdown(&buf, loadFixtureMachine(t)))
	out := buf.String()

	require.True(t, strings.HasPrefix(out, "# _fixture machine — reader's view\n\n"), out)
	require.Contains(t, out, "2 states, 2 events, 2 transitions, 6 authored cells.")
	require.Contains(t, out, "Generated by rolloutspec-grid; do not edit — regenerate with `make rolloutspec-render MACHINE=_fixture`.")
	require.Contains(t, out, "## States at a glance\n")
	require.Contains(t, out, "## Idle\n")
	require.Contains(t, out, "## Working\n")
}

func TestEmitMarkdownInvariantsTable(t *testing.T) {
	var buf bytes.Buffer
	require.NoError(t, emitMarkdown(&buf, loadFixtureMachine(t)))
	out := buf.String()

	glance := strings.Index(out, "## States at a glance\n")
	invariants := strings.Index(out, "## Invariants\n")
	require.GreaterOrEqual(t, invariants, 0, out)
	require.Greater(t, invariants, glance, "invariants table follows the states overview")
	require.Less(t, invariants, strings.Index(out, "## Idle\n"))
	require.Contains(t, out, "| id | statement |\n")
	require.Contains(t, out, "| ready.count.matches.pods |")
}

