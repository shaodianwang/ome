func TestEmitMarkdownHowYouGetHereAndLeave(t *testing.T) {
	var buf bytes.Buffer
	require.NoError(t, emitMarkdown(&buf, loadFixtureMachine(t)))
	out := buf.String()

	idle := stateSection(t, out, "Idle")
	require.Contains(t, idle, "**How you get here**\n\n"+
		"- from `Working` on timer.deadline when the step deadline elapses  (`working-to-idle`)\n")
	require.Contains(t, idle, "**How you leave**\n\n"+
		"- on pod.ready[source] when a source pod reports Ready → `Working`  (`idle-to-working`)\n")

	working := stateSection(t, out, "Working")
	require.Contains(t, working, "- from `Idle` on pod.ready[source] when a source pod reports Ready  (`idle-to-working`)\n")
	require.Contains(t, working, "- on timer.deadline when the step deadline elapses → `Idle`  (`working-to-idle`)\n")
}

