func TestEmitMarkdownWhatElseHappensExcludesIgnoreAndNA(t *testing.T) {
	var buf bytes.Buffer
	require.NoError(t, emitMarkdown(&buf, loadFixtureMachine(t)))
	out := buf.String()

	idle := stateSection(t, out, "Idle")
	table := idle[strings.Index(idle, "**What else happens here**"):strings.Index(idle, "**Ignored here**")]

	// The before-window cell (outcome transition) is the only non-ignore,
	// non-n/a authored cell for Idle; the boundary/after ignore cells for
	// pod.ready[source] and the pod.ready[target] ignore cell must not
	// appear as table rows.
	require.Contains(t, table, "| pod.ready[source] | before |  | transition | Working |  |\n")
	require.Equal(t, 1, strings.Count(table, "pod.ready[source]"))
	require.NotContains(t, table, "pod.ready[target]")
}

