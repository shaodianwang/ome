#!/usr/bin/env bash
# Generate a PVC + Manifold download Job for a given checkpoint URI.
# Input is a manifold:// URI; the job's --s3_download_base_uri uses the same path
# with the scheme swapped to s3:// (download.py + --provider=manifold). download.py
# appends "/checkpoint" itself, so a trailing "/checkpoint" in the input is stripped
# from the base URI. Typical input:
#   manifold://fair_llms_prod/tree/vllm_test/<model-id>/checkpoint_0000150/checkpoint
# PRINTS YAML TO STDOUT ONLY — it never touches a cluster. Review, then apply
# yourself. See README.md for prerequisites (Aqueduct cert secret, cloud_oss, SC).
#
#   ./gen-download.sh <checkpoint-uri> [flags] > /tmp/dl.yaml
#   kubectl --context cw/msl-cw-use2-2 -n prod apply -f /tmp/dl.yaml   # you run this
#
# Flags:
#   --name <pvc-name>     PVC name (default: auto-derived from the URI, ckpt-<slug>)
#   --size <N>            PVC size (default: 3Ti)
#   --namespace <ns>      target namespace (default: prod)
#   --node-type <t>       metafb.cloud/node-type nodeSelector (default: gb300)
#   --user <u>            owner label + job-name suffix (default: $USER)
#   --image <ref>         downloader image (default: msl_infra/model-downloader:latest)
#   --provider <p>        download.py provider (default: manifold)
set -euo pipefail

DEF_IMAGE="168653207203.dkr.ecr.us-east-2.amazonaws.com/msl_infra/model-downloader:latest"
SIZE="3Ti"; NAMESPACE="prod"; NODE_TYPE="gb300"; USER_NAME="${USER:-unknown}"
IMAGE="$DEF_IMAGE"; PROVIDER="manifold"; PVC_NAME=""
URI=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --name) PVC_NAME="$2"; shift 2;;
    --size) SIZE="$2"; shift 2;;
    --namespace) NAMESPACE="$2"; shift 2;;
    --node-type) NODE_TYPE="$2"; shift 2;;
    --user) USER_NAME="$2"; shift 2;;
    --image) IMAGE="$2"; shift 2;;
    --provider) PROVIDER="$2"; shift 2;;
    -h|--help) sed -n '2,20p' "$0"; exit 0;;
    -*) echo "unknown flag: $1" >&2; exit 2;;
    *) URI="$1"; shift;;
  esac
done

[[ -n "$URI" ]] || { echo "error: missing <checkpoint-uri>. See --help." >&2; exit 2; }

# Job arg uses s3:// with the same path (input is manifold://; swap the scheme).
# download.py appends "/checkpoint" itself, so strip a trailing literal "checkpoint"
# segment from the base URI (else it fetches .../checkpoint/checkpoint = nothing).
DL_URI="s3://${URI#*://}"
DL_URI="${DL_URI%/}"; DL_URI="${DL_URI%/checkpoint}"

# slug: lowercase, non-alnum -> '-', collapse, trim. Used for auto names.
slug() { echo "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//'; }
trunc() { echo "$1" | cut -c1-"$2" | sed -E 's/-+$//'; }

# Derive names from the URI path. Inputs look like
#   manifold://fair_llms_prod/tree/vllm_test/<model-id>/checkpoint_0000150/checkpoint
# i.e. a trailing literal "checkpoint" may follow the numbered "checkpoint_NNNN".
# Scan for the checkpoint_NNNN segment (anywhere); model-id is the segment before it.
path="${URI#*://}"; path="${path%/}"                # strip scheme://, trailing slash
IFS='/' read -ra segs <<<"$path"
ckpt_num=""; model_seg=""
for i in "${!segs[@]}"; do
  if [[ "${segs[$i]}" =~ ^checkpoint[_-]?0*([0-9]+)$ ]]; then
    ckpt_num="${BASH_REMATCH[1]}"
    (( i > 0 )) && model_seg="${segs[$((i-1))]}"
  fi
done
if [[ -z "$ckpt_num" ]]; then                       # no checkpoint_NNNN: fall back to last 2
  nf=${#segs[@]}
  (( nf >= 2 )) && model_seg="${segs[$((nf-2))]}"
  ckpt_sfx="-$(slug "${segs[$((nf-1))]}")"
else
  ckpt_sfx="-ckpt${ckpt_num}"
fi
model_slug="$(slug "$model_seg")"
if [[ -z "$PVC_NAME" ]]; then                       # ckpt-<model>-ckptNNN, <=57, suffix kept
  PVC_NAME="ckpt-$(trunc "$model_slug" $((57 - 5 - ${#ckpt_sfx})))${ckpt_sfx}"
fi
PVC_NAME="$(trunc "$PVC_NAME" 57)"
body="${PVC_NAME#ckpt-}"                            # dl-<body>-<user>, <=57, user kept
JOB_NAME="dl-$(trunc "$body" $((57 - 3 - 1 - ${#USER_NAME})))-${USER_NAME}"

# Sanity: k8s RFC1123 names.
for n in "$PVC_NAME" "$JOB_NAME"; do
  [[ "$n" =~ ^[a-z0-9]([-a-z0-9]*[a-z0-9])?$ ]] || {
    echo "error: derived name '$n' is not a valid k8s name; pass --name." >&2; exit 2; }
done

echo "# generated by gen-download.sh — REVIEW then apply manually (prod!)" >&2
echo "#   pvc=$PVC_NAME  job=$JOB_NAME  ns=$NAMESPACE  size=$SIZE  download_uri=$DL_URI" >&2

cat <<YAML
apiVersion: v1
kind: PersistentVolumeClaim
metadata:
  name: ${PVC_NAME}
  namespace: ${NAMESPACE}
spec:
  accessModes: [ReadWriteMany]
  storageClassName: shared-vast
  volumeMode: Filesystem
  resources:
    requests:
      storage: ${SIZE}
---
apiVersion: batch/v1
kind: Job
metadata:
  name: ${JOB_NAME}
  namespace: ${NAMESPACE}
  labels:
    app.kubernetes.io/component: model-downloader
    user: ${USER_NAME}
spec:
  completions: 1
  parallelism: 1
  backoffLimit: 3
  template:
    metadata:
      labels:
        app.kubernetes.io/component: model-downloader
        user: ${USER_NAME}
    spec:
      restartPolicy: Never
      nodeSelector:
        metafb.cloud/node-type: ${NODE_TYPE}
      tolerations:
        - {key: nvidia.com/gpu, operator: Exists, effect: NoSchedule}
      containers:
        - name: model-downloader
          image: ${IMAGE}
          command: ["bash", "-c"]
          args:
            - |
              set -euo pipefail
              mkdir -p ~/.aws
              cat > ~/.aws/config <<'AWSCFG'
              [default]
              credential_process = /opt/cf/cloud_oss/cloud_oss cat generate cat --verifier-identity SERVICE_IDENTITY:manifold.blobstore --verifier-identity SERVICE_IDENTITY:memcache --verifier-identity SERVICE_IDENTITY:ai_security/ads_token_service_v2 -o cli --timeout-secs 3600
              region = us-east-2
              AWSCFG
              exec /download.py \\
                checkpoint \\
                --provider=${PROVIDER} \\
                --local_dir=/mnt/models \\
                --s3_download_base_uri=${DL_URI}
          env:
            - {name: PYTHONUNBUFFERED, value: "1"}
            - {name: HOME, value: /tmp}
            - {name: THRIFT_TLS_SRV_CA_PATH, value: /etc/ssl/certs/ca-bundle.crt}
            - {name: THRIFT_TLS_CL_CERT_PATH, value: /var/facebook/x509_svc/tls.crt}
            - {name: THRIFT_TLS_CL_KEY_PATH, value: /var/facebook/x509_svc/tls.key}
          resources:
            requests: {cpu: "4", memory: 8Gi}
            limits: {cpu: "8", memory: 16Gi}
          volumeMounts:
            - {name: models, mountPath: /mnt/models}
            - {name: cloud-oss, mountPath: /opt/cf/cloud_oss, readOnly: true}
            - {name: tmp, mountPath: /tmp}
            - {name: tls-cert, mountPath: /var/facebook/x509_svc/}
      volumes:
        - name: models
          persistentVolumeClaim:
            claimName: ${PVC_NAME}
        - name: cloud-oss
          hostPath: {path: /opt/cf/cloud_oss, type: Directory}
        - name: tls-cert
          secret: {secretName: inference-aqueduct-cert, defaultMode: 420}
        - name: tmp
          emptyDir: {}
YAML
