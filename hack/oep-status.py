#!/usr/bin/env python3
"""Render oeps/STATUS.md from every oeps/*/oep.yaml.

Reads only the flat scalar keys each oep.yaml is guaranteed to carry
(title, oep-number, status, stage, latest-milestone), the `authors:` list,
and the `# state:` comment under `status:`, so it needs no YAML library.
Nested keys such as `milestone:` are skipped.

    hack/oep-status.py          # rewrite oeps/STATUS.md
    hack/oep-status.py --check  # exit 1 if oeps/STATUS.md is stale
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OEPS = ROOT / "oeps"
OUT = OEPS / "STATUS.md"

SCALAR = re.compile(r"^([a-z][a-z-]*):\s*(.*?)\s*$")
STATE = re.compile(r"^#\s*state:\s*(.*?)\s*$")
ITEM = re.compile(r"^\s+-\s+(.*?)\s*$")

STATUS_ORDER = ["implemented", "implementable", "provisional", "withdrawn"]


def unquote(value):
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def read_oep(path):
    fields = {"dir": path.parent.name, "state": "", "authors": []}
    in_authors = False
    for line in path.read_text().splitlines():
        m = STATE.match(line)
        if m:
            fields["state"] = m.group(1)
            continue
        m = SCALAR.match(line)
        if m:
            in_authors = m.group(1) == "authors"
            if m.group(2):
                fields[m.group(1)] = unquote(m.group(2))
            continue
        m = ITEM.match(line)
        if m and in_authors:
            fields["authors"].append(unquote(m.group(1)))
    missing = [k for k in ("title", "oep-number", "status", "stage") if k not in fields]
    if missing:
        sys.exit(f"{path}: missing {', '.join(missing)}")
    if fields["status"] not in STATUS_ORDER:
        sys.exit(f"{path}: unknown status {fields['status']!r}; expected one of {STATUS_ORDER}")
    if not fields["state"]:
        sys.exit(f"{path}: missing '# state:' comment under status:")
    if not fields["authors"]:
        sys.exit(f"{path}: missing 'authors:' list")
    return fields


def number_key(num):
    return tuple(int(part) for part in num.split("."))


def render(oeps):
    counts = {s: sum(1 for o in oeps if o["status"] == s) for s in STATUS_ORDER}
    lines = [
        "# OEP status",
        "",
        "Generated by `make oep-status` from every `oeps/*/oep.yaml`; do not hand-edit.",
        "Each row's owner is that OEP's `authors:` list and its evidence is the",
        "`# state:` comment in its `oep.yaml`.",
        "",
        "Counts: " + ", ".join(f"{counts[s]} {s}" for s in STATUS_ORDER) + ".",
        "",
        "| OEP | Title | Owner | Status | Stage | Milestone | Evidence |",
        "|---|---|---|---|---|---|---|",
    ]
    for o in oeps:
        lines.append(
            "| [{num}]({dir}/) | {title} | {owner} | {status} | {stage} | {ms} | {state} |".format(
                num=o["oep-number"],
                dir=o["dir"],
                title=o["title"].replace("|", "\\|"),
                owner=", ".join(o["authors"]),
                status=o["status"],
                stage=o["stage"],
                ms=o.get("latest-milestone", ""),
                state=o["state"].replace("|", "\\|"),
            )
        )
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if STATUS.md is stale instead of writing it")
    args = parser.parse_args()

    oeps = sorted((read_oep(p) for p in OEPS.glob("*/oep.yaml")), key=lambda o: number_key(o["oep-number"]))
    text = render(oeps)
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale; run `make oep-status`")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(oeps)} OEPs)")


if __name__ == "__main__":
    main()
